import { createHash } from 'node:crypto';
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { deflateSync } from 'node:zlib';

const root = new URL('../', import.meta.url);
const file = path => new URL(path, root);
const word = n => { const bytes = Buffer.alloc(4); bytes.writeUInt32BE(n >>> 0); return bytes; };
function chunk(type, data) {
  const body = Buffer.concat([Buffer.from(type), data]);
  let crc = -1;
  for (const byte of body) {
    crc ^= byte;
    for (let bit = 0; bit < 8; bit++) crc = (crc >>> 1) ^ (0xedb88320 & -(crc & 1));
  }
  return Buffer.concat([word(data.length), body, word(~crc)]);
}
function triangle(x, y, points) {
  const sides = points.map(([ax, ay], i) => {
    const [bx, by] = points[(i + 1) % 3];
    return (bx - ax) * (y - ay) - (by - ay) * (x - ax);
  });
  return sides.every(s => s >= 0) || sides.every(s => s <= 0);
}
function icon(size, maskable) {
  const stride = 1 + size * 3;
  const raw = Buffer.alloc(stride * size);
  for (let y = 0; y < size; y++) for (let x = 0; x < size; x++) {
    const scale = maskable ? 1.18 : 1;
    const u = (x / size - .5) * scale + .5, v = (y / size - .5) * scale + .5;
    let rgb = [18 + 14 * y / size, 38 + 35 * y / size, 79 + 86 * y / size];
    if (triangle(u, v, [[.25,.46],[.77,.27],[.63,.72]])) rgb = [248, 252, 255];
    if (triangle(u, v, [[.42,.55],[.77,.27],[.49,.62]])) rgb = [131, 174, 252];
    if (triangle(u, v, [[.42,.55],[.49,.62],[.43,.71]])) rgb = [192, 217, 255];
    raw.set(rgb, y * stride + 1 + x * 3);
  }
  return Buffer.concat([Buffer.from([137,80,78,71,13,10,26,10]),
    chunk('IHDR', Buffer.concat([word(size), word(size), Buffer.from([8,2,0,0,0])])),
    chunk('IDAT', deflateSync(raw)), chunk('IEND', Buffer.alloc(0))]);
}

async function walk(path) {
  const entries = await readdir(file(`${path}/`), { withFileTypes: true });
  const groups = await Promise.all(entries.filter(entry => !entry.name.startsWith('.')).map(entry => {
    const child = `${path}/${entry.name}`;
    return entry.isDirectory() ? walk(child) : child;
  }));
  return groups.flat();
}

const check = process.argv.includes('--check');
async function generate(path, bytes) {
  if (check) {
    if (!(await readFile(file(path))).equals(Buffer.from(bytes))) throw new Error(`${path} is stale. Run npm run assets.`);
  } else await writeFile(file(path), bytes);
}
if (!check) await mkdir(file('icons/'), { recursive: true });
await generate('icons/icon-192.png', icon(192, false));
await generate('icons/icon-512.png', icon(512, false));
await generate('icons/maskable-512.png', icon(512, true));
const paths = ['index.html', 'style.css', 'manifest.webmanifest', 'sw.js', ...await walk('icons'), ...await walk('src'), ...await walk('vendor')].sort();
const hash = createHash('sha256');
for (const path of paths) hash.update(path).update('\0').update(await readFile(file(path))).update('\0');
const revision = hash.digest('hex').slice(0, 20);
const manifest = `// Generated by npm run assets.\nself.PAPERPLANE_ASSETS = ${JSON.stringify({ revision, paths: [...paths, 'precache.js'].sort().map(path => `./${path}`) }, null, 2)};\n`;
await generate('precache.js', manifest);
console.log(`${check ? 'Verified' : 'Generated'} ${paths.length + 1} offline assets (${revision}).`);
